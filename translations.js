// setting: "auto" or a key of `strings`; systemLocale: e.g. "pt_BR".
function resolve(setting, systemLocale) {
    if (setting && setting !== "auto" && strings[setting])
        return setting;
    const lang = String(systemLocale || "en").split(/[_-]/)[0].toLowerCase();
    return strings[lang] ? lang : "en";
}

// tr(lang, key, arg1, arg2, ...) replaces %1, %2, ... with the args.
function tr(lang, key) {
    const table = strings[lang] || strings.en;
    let s = table[key] || strings.en[key] || key;
    for (let i = 2; i < arguments.length; i++)
        s = s.replace("%" + (i - 1), arguments[i]);
    return s;
}
